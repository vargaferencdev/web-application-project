import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * One-off helper: finds a cover image for every title of the catalog and writes a Flyway migration.
 *
 * How it works
 *   1. reads the titles from the running AniTrack app (GET /api/media, public endpoint)
 *   2. asks the public AniList API (https://anilist.co) for the best match of each title
 *   3. writes src/main/resources/db/migration/V4__covers.sql with one UPDATE per title
 *
 * Run it from the project root while the app is running:
 *      java tools/FetchCovers.java
 *
 * The migration file contains the matched AniList title in a comment, so the result can be checked by eye.
 * Titles that were not found keep their placeholder (the frontend shows the first letter).
 */
public class FetchCovers {

    private static final String APP = System.getProperty("app", "http://localhost:8080");
    private static final String ANILIST = System.getProperty("anilist", "https://graphql.anilist.co");
    private static final Path OUTPUT = Path.of(System.getProperty("out",
            "src/main/resources/db/migration/V4__covers.sql"));

    private static final HttpClient HTTP = HttpClient.newHttpClient();

    private static final Pattern TITLE = Pattern.compile(
            "\"id\"\\s*:\\s*(\\d+)\\s*,\\s*\"title\"\\s*:\\s*\"((?:[^\"\\\\]|\\\\.)*)\"\\s*,\\s*\"mediaType\"\\s*:\\s*\"(\\w+)\"\\s*,\\s*\"format\"\\s*:\\s*\"(\\w+)\"");
    private static final Pattern TOTAL_PAGES = Pattern.compile("\"totalPages\"\\s*:\\s*(\\d+)");
    private static final Pattern COVER = Pattern.compile("\"large\"\\s*:\\s*\"([^\"]+)\"");
    private static final Pattern ROMAJI = Pattern.compile("\"romaji\"\\s*:\\s*(null|\"((?:[^\"\\\\]|\\\\.)*)\")");

    record Item(String title, String type, String format) {
    }

    public static void main(String[] args) throws Exception {
        if (Files.exists(OUTPUT)) {
            System.out.println(OUTPUT + " already exists. Flyway checks the checksum of applied migrations,");
            System.out.println("so do not overwrite it. Delete it first if it was never applied.");
            return;
        }

        List<Item> items = loadTitles();
        System.out.println("Found " + items.size() + " titles in the catalog.\n");

        StringBuilder sql = new StringBuilder();
        sql.append("-- =====================================================================\n");
        sql.append("-- AniTrack - V4__covers.sql\n");
        sql.append("-- Cover image URLs, generated by tools/FetchCovers.java from the public AniList API.\n");
        sql.append("-- The comment above each statement is the title AniList matched.\n");
        sql.append("-- =====================================================================\n\n");

        int found = 0;
        for (Item item : items) {
            if (item.title().startsWith("Demo ")) {
                continue;   // placeholder entries of the seed data
            }
            String[] match = lookup(item);
            if (match == null) {
                System.out.printf("  --  %-45s (not found)%n", item.title());
            } else {
                found++;
                System.out.printf("  ok  %-45s -> %s%n", item.title(), match[0]);
                sql.append("-- ").append(item.type()).append(": ").append(item.title())
                        .append("  =>  ").append(match[0].replace("\n", " ")).append('\n');
                sql.append("UPDATE media SET cover_image_url = ").append(quote(match[1]))
                        .append(" WHERE title = ").append(quote(item.title()))
                        .append(" AND media_type = ").append(quote(item.type())).append(";\n\n");
            }
            Thread.sleep(900);   // AniList allows about 90 requests per minute
        }

        Files.createDirectories(OUTPUT.getParent());
        Files.writeString(OUTPUT, sql.toString(), StandardCharsets.UTF_8);
        System.out.println("\nDone: " + found + " covers written to " + OUTPUT);
        System.out.println("Check the matches, then restart the app: Flyway applies V4 automatically.");
    }

    private static List<Item> loadTitles() throws Exception {
        List<Item> items = new ArrayList<>();
        int page = 0;
        int totalPages = 1;
        while (page < totalPages) {
            String body = send(HttpRequest.newBuilder(URI.create(APP + "/api/media?size=50&page=" + page)).GET().build());
            Matcher pages = TOTAL_PAGES.matcher(body);
            if (pages.find()) {
                totalPages = Integer.parseInt(pages.group(1));
            }
            Matcher matcher = TITLE.matcher(body);
            while (matcher.find()) {
                items.add(new Item(unescape(matcher.group(2)), matcher.group(3), matcher.group(4)));
            }
            page++;
        }
        return items;
    }

    /** Returns {matched title, cover url}, or null when AniList has no match. */
    private static String[] lookup(Item item) throws Exception {
        String query = "query($s:String,$t:MediaType,$f:MediaFormat){Media(search:$s,type:$t,format:$f)"
                + "{title{romaji} coverImage{large}}}";
        String json = "{\"query\":\"" + query + "\",\"variables\":{\"s\":" + jsonString(item.title())
                + ",\"t\":\"" + item.type() + "\",\"f\":\"" + item.format() + "\"}}";
        HttpRequest request = HttpRequest.newBuilder(URI.create(ANILIST))
                .header("Content-Type", "application/json")
                .header("Accept", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString(json))
                .build();
        for (int attempt = 0; attempt < 3; attempt++) {
            HttpResponse<String> response = HTTP.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() == 429) {
                System.out.println("  (rate limited, waiting 60 seconds)");
                Thread.sleep(60_000);
                continue;
            }
            if (response.statusCode() != 200) {
                return null;   // 404 = no such title
            }
            Matcher cover = COVER.matcher(response.body());
            if (!cover.find()) {
                return null;
            }
            Matcher romaji = ROMAJI.matcher(response.body());
            String name = romaji.find() && romaji.group(2) != null ? unescape(romaji.group(2)) : "?";
            return new String[]{name, cover.group(1).replace("\\/", "/")};
        }
        return null;
    }

    private static String send(HttpRequest request) throws Exception {
        HttpResponse<String> response = HTTP.send(request, HttpResponse.BodyHandlers.ofString());
        if (response.statusCode() != 200) {
            throw new IllegalStateException("Unexpected answer " + response.statusCode() + " from " + request.uri()
                    + " (is the app running?)");
        }
        return response.body();
    }

    private static String quote(String value) {
        return "'" + value.replace("'", "''") + "'";
    }

    private static String jsonString(String value) {
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }

    private static String unescape(String value) {
        return value.replace("\\\"", "\"").replace("\\\\", "\\");
    }
}
